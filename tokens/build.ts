
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type ColorToken = { light: string; dark: string };
export type Tokens = {
  color: Record<string, ColorToken>;
} & Record<"font" | "fontSize" | "fontWeight" | "lineHeight" | "space" | "radius" | "size", Record<string, string>>;

const root = import.meta.dirname + "/../";
const DARK = "@media (prefers-color-scheme: dark)";
const HEADER = "// GENERATED by tokens/build.ts from tokens/tokens.json. Do not edit.\n";
const groups = ["font", "fontSize", "fontWeight", "lineHeight", "space", "radius", "size"] as const;

export function loadTokens(): Tokens {
  return JSON.parse(readFileSync(root + "tokens/tokens.json", "utf8"));
}

const cssName = (group: string, key: string) => `--paper-${group.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}-${key}`;

export function toStylex(t: Tokens): string {
  const colors = Object.entries(t.color)
    .map(([k, v]) => `  ${JSON.stringify(k)}: { default: ${JSON.stringify(v.light)}, ${JSON.stringify(DARK)}: ${JSON.stringify(v.dark)} },`)
    .join("\n");
  let out = `${HEADER}import * as stylex from "@stylexjs/stylex";\n\nexport const color = stylex.defineVars({\n${colors}\n});\n`;
  for (const g of groups) {
    const body = Object.entries(t[g]).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
    out += `\nexport const ${g} = stylex.defineVars({\n${body}\n});\n`;
  }
  return out;
}

export function toCss(t: Tokens): string {
  const light = Object.entries(t.color).map(([k, v]) => `  ${cssName("color", k)}: ${v.light};`);
  const dark = Object.entries(t.color).map(([k, v]) => `    ${cssName("color", k)}: ${v.dark};`);
  const rest = groups.flatMap((g) => Object.entries(t[g]).map(([k, v]) => `  ${cssName(g, k)}: ${v};`));
  return `/* GENERATED by tokens/build.ts. For non-StyleX consumers. Do not edit. */\n:root {\n${[...light, ...rest].join("\n")}\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n${dark.join("\n")}\n  }\n}\n`;
}

export const outputs = (t: Tokens) => ({
  "registry/components/tokens.stylex.ts": toStylex(t),
  "tokens/tokens.css": toCss(t),
});

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [file, content] of Object.entries(outputs(loadTokens()))) {
    const path = root + file;
    if (check) {
      let current = "";
      try { current = readFileSync(path, "utf8"); } catch { /* missing */ }
      if (current !== content) { console.error(`stale: ${file} (run pnpm generate)`); stale = true; }
    } else writeFileSync(path, content);
  }
  if (stale) process.exit(1);
}
